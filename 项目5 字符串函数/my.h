#ifndef MY_H
#define MY_H

/*
 * 字符串长度计算函数
 * 参数: s - 字符串指针
 * 返回值: 字符串长度（不包括'\0'）
 */
int mylen(char *s);

/*
 * 字符串比较函数
 * 参数: s1, s2 - 要比较的两个字符串
 * 返回值: 
 *   1  - s1 > s2
 *   0  - s1 == s2
 *  -1  - s1 < s2
 */
int mycmp(char *s1, char *s2);

/*
 * 字符串复制函数
 * 参数: s1 - 目标字符串，s2 - 源字符串
 * 返回值: 目标字符串s1的指针
 * 注意: 会完全覆盖s1原有内容
 */
char *mycpy(char *s1, char *s2);

/*
 * 字符串连接函数
 * 参数: s1 - 目标字符串，s2 - 要连接的源字符串
 * 返回值: 连接后的字符串s1的指针
 * 注意: 将s2的内容追加到s1的末尾
 */
char *mycat(char *s1, char *s2);

/*
 * 指定长度字符串比较函数
 * 参数: s1, s2 - 要比较的字符串，len - 比较的字符数
 * 返回值: 同mycmp
 * 注意: 只比较前len个字符
 */
int myncmp(char *s1, char *s2, int len);

/*
 * 指定长度字符串复制函数
 * 参数: s1 - 目标字符串，s2 - 源字符串，len - 要复制的最大字符数
 * 返回值: 目标字符串s1的指针
 * 注意: 最多复制len个字符，如果不足len个，剩余部分用'\0'填充
 */
char *myncpy(char *s1, char *s2, int len);

/*
 * 指定长度字符串连接函数
 * 参数: s1 - 目标字符串，s2 - 要连接的源字符串，len - 要连接的最大字符数
 * 返回值: 连接后的字符串s1的指针
 * 注意: 从s2中最多取len个字符连接到s1末尾
 */
char *myncat(char *s1, char *s2, int len);

/*
 * 字符查找函数（正向查找）
 * 参数: s - 要查找的字符串，c - 要查找的字符
 * 返回值: 指向第一个匹配字符的指针，如果未找到返回NULL
 */
char *mychr(char *s, char c);

/*
 * 字符查找函数（反向查找）
 * 参数: s - 要查找的字符串，c - 要查找的字符
 * 返回值: 指向最后一个匹配字符的指针，如果未找到返回NULL
 */
char *myrchr(char *s, char c);

#endif
